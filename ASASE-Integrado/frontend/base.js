const translationPairs = Object.entries(englishTranslations).sort(
  (a, b) => b[0].length - a[0].length,
);
let language = (() => {
  try {
    return localStorage.getItem("asase.language") === "en" ? "en" : "es";
  } catch {
    return "es";
  }
})();
function translateString(input) {
  if (language !== "en" || typeof input !== "string") return input;
  // Traducción de frases enteras y, para textos dinámicos, de sus segmentos.
  if (Object.hasOwn(englishTranslations, input))
    return englishTranslations[input];
  let result = input;
  for (const [es, en] of translationPairs)
    if (result.includes(es)) result = result.split(es).join(en);
  return result;
}
function languageSwitcher() {
  return `<div class="language-switch" role="group" aria-label="Idioma / Language"><button type="button" data-language="es" lang="es" aria-pressed="${language === "es"}" class="${language === "es" ? "active" : ""}">ES</button><button type="button" data-language="en" lang="en" aria-pressed="${language === "en"}" class="${language === "en" ? "active" : ""}">EN</button></div>`;
}
function translateUI(root) {
  document.documentElement.lang = language;
  document.title =
    language === "en"
      ? "asase. — Intelligence to protect agricultural productivity"
      : "asase. — Inteligencia para proteger la productividad agrícola";
  if (language !== "en") return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    if (node.parentElement?.closest(".language-switch, [data-api-text]"))
      continue;
    node.nodeValue = translateString(node.nodeValue);
  }
  for (const el of root.querySelectorAll(
    "[aria-label],[title],[placeholder]",
  )) {
    if (el.closest(".language-switch")) continue;
    for (const attr of ["aria-label", "title", "placeholder"]) {
      const value = el.getAttribute(attr);
      if (value !== null) el.setAttribute(attr, translateString(value));
    }
  }
}

